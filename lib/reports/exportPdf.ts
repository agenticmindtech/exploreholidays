import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import type { ReportColumn, ReportConfig, ReportGroupRow, Settings } from "@/lib/types";
import { formatMoney } from "@/lib/utils/format";

function todayStamp(): string {
  return new Date().toISOString().slice(0, 10);
}

const PRIMARY_800: [number, number, number] = [15, 79, 87];
const SUBTLE_ROW: [number, number, number] = [237, 250, 250];

export function exportPdf<Row extends Record<string, unknown>>(
  config: ReportConfig,
  rows: Row[],
  groups: ReportGroupRow<Row>[] | undefined,
  summary: Record<string, number>,
  filtersEcho: string,
  settings: Settings
): void {
  const columns = config.columns as ReportColumn<Row>[];
  const landscape = columns.length > 7;
  const doc = new jsPDF({ orientation: landscape ? "landscape" : "portrait", unit: "pt", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header band
  doc.setFillColor(...PRIMARY_800);
  doc.rect(0, 0, pageWidth, 56, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.text(settings.agencyName, 24, 24);
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text(config.title, 24, 40);
  doc.setFontSize(9);
  doc.text(`Printed ${new Date().toLocaleString()}`, pageWidth - 24, 24, { align: "right" });

  doc.setTextColor(20, 20, 20);
  doc.setFontSize(9);
  doc.text(filtersEcho, 24, 70);

  const body: (string | number)[][] = [];
  const moneyColIndexes: number[] = [];
  columns.forEach((c, i) => {
    if (c.money) moneyColIndexes.push(i);
  });

  function pushRow(row: Row) {
    body.push(columns.map((c) => pdfCellValue(row, c)));
  }

  if (groups && groups.length > 0) {
    for (const group of groups) {
      body.push([`${group.label}`, ...columns.slice(1).map((c) => (c.money ? formatMoney(group.subtotal[c.summaryKey ?? c.key] ?? 0) : ""))]);
      for (const row of group.rows) pushRow(row);
    }
  } else {
    for (const row of rows) pushRow(row);
  }

  const totalRow = columns.map((c, i) => {
    if (i === 0) return "GRAND TOTAL";
    const summaryKey = c.summaryKey ?? c.key;
    if (c.money && summary[summaryKey] !== undefined) return formatMoney(summary[summaryKey]);
    return "";
  });
  body.push(totalRow);
  const totalRowIndex = body.length - 1;

  autoTable(doc, {
    startY: 84,
    head: [columns.map((c) => c.label)],
    body,
    theme: "striped",
    styles: { font: "helvetica", fontSize: 8, cellPadding: 5 },
    headStyles: { fillColor: PRIMARY_800, textColor: 255, fontStyle: "bold" },
    alternateRowStyles: { fillColor: SUBTLE_ROW },
    columnStyles: Object.fromEntries(moneyColIndexes.map((i) => [i, { halign: "right", font: "courier" }])),
    didParseCell: (data) => {
      if (data.row.index === totalRowIndex && data.section === "body") {
        data.cell.styles.fontStyle = "bold";
        data.cell.styles.fillColor = [226, 240, 240];
      }
    },
  });

  // "Page X of Y" must be written AFTER autoTable finishes, not from its didDrawPage
  // hook — at the time an early page is drawn, later pages don't exist yet, so
  // doc.getNumberOfPages() inside the hook would report an incomplete total on every
  // page but the last. Looping over the final page count here is the standard fix.
  const pageHeight = doc.internal.pageSize.getHeight();
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(120, 120, 120);
    doc.text("Generated by TravelDesk Pro", 24, pageHeight - 16);
    doc.text(`Page ${i} of ${pageCount}`, pageWidth - 24, pageHeight - 16, { align: "right" });
  }

  doc.save(`${config.id}_${todayStamp()}.pdf`);
}

function pdfCellValue<Row extends Record<string, unknown>>(row: Row, column: ReportColumn<Row>): string | number {
  const v = row[column.key];
  if (column.money) return formatMoney(typeof v === "number" ? v : Number(v) || 0);
  if (v === null || v === undefined) return "—";
  if (typeof v === "object") return JSON.stringify(v);
  return String(v);
}
